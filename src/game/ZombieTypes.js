export function pickZombieType() {
  const entries = Object.values(ZOMBIE_TYPES)
  const total = entries.reduce((sum, t) => sum + t.weight, 0)
  let roll = Math.random() * total
  for (const t of entries) {
    roll -= t.weight
    if (roll <= 0) return t
  }
  return entries[0]
}
